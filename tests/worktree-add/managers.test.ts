const CLASSIC_LOCK = '# THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.\n# yarn lockfile v1\n\n\n';
const BERRY_LOCK =
    '# This file is generated by running "yarn install" inside your project.\n\n__metadata:\n  version: 8\n';
const EMPTY_PACKAGE = JSON.stringify({ name: 'wta-fixture', version: '1.0.0' });

function project(t: TestContext, files: Readonly<Record<string, string>>): string {
    const dir = tempRoot(t);
    for (const [name, content] of Object.entries(files)) {
        fs.mkdirSync(path.dirname(path.join(dir, name)), { recursive: true });
        fs.writeFileSync(path.join(dir, name), content);
    }
    return dir;
}

function expectManager(choice: ManagerChoice, manager: ManagerName): ExpectedVersion | undefined {
    assert.equal(choice.kind, 'manager', choice.kind === 'conflict' ? choice.reason : '');
    if (choice.kind !== 'manager') {
        throw new Error('unreachable');
    }
    assert.equal(choice.manager, manager);
    return choice.expected;
}

function expectVersion(choice: ManagerChoice, manager: ManagerName): ExpectedVersion {
    const expected = expectManager(choice, manager);
    assert.ok(expected, 'an expectation is set');
    return expected;
}

function expectConflict(choice: ManagerChoice): string {
    assert.equal(choice.kind, 'conflict');
    if (choice.kind !== 'conflict') {
        throw new Error('unreachable');
    }
    return choice.reason;
}

function toolOrSkip(t: TestContext, name: string): string | undefined {
    try {
        return realToolPath(name, process.env);
    } catch {
        t.skip(`${name} is not installed`);
        return;
    }
}

function stubEnv(binDir: string): Env {
    return { PATH: binDir };
}

await test('packageManager pnpm with a hash pins pnpm to its major', (t) => {
    const dir = project(t, {
        'package.json': JSON.stringify({ packageManager: 'pnpm@10.33.0+sha512.abc' }),
        'pnpm-lock.yaml': "lockfileVersion: '9.0'\n",
    });
    const expected = expectVersion(chooseManager(dir, 'js', ['pnpm-lock.yaml']), 'pnpm');
    assert.equal(expected.accepts(10), true);
    assert.equal(expected.accepts(9), false);
    assert.equal(expected.text, 'pnpm 10');
});


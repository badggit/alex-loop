await test('older pnpm lockfileVersions map to their pnpm majors', (t) => {
    const six = project(t, { 'package.json': EMPTY_PACKAGE, 'pnpm-lock.yaml': "lockfileVersion: '6.0'\n" });
    const sixExpected = expectVersion(chooseManager(six, 'js', ['pnpm-lock.yaml']), 'pnpm');
    assert.deepEqual(
        [7, 8, 9].map((major) => sixExpected.accepts(major)),
        [false, true, false]
    );
    const five = project(t, { 'package.json': EMPTY_PACKAGE, 'pnpm-lock.yaml': 'lockfileVersion: 5.4\n' });
    const fiveExpected = expectVersion(chooseManager(five, 'js', ['pnpm-lock.yaml']), 'pnpm');
    assert.deepEqual(
        [5, 6, 7, 8].map((major) => fiveExpected.accepts(major)),
        [false, true, true, false]
    );
    const other = project(t, { 'package.json': EMPTY_PACKAGE, 'pnpm-lock.yaml': "lockfileVersion: '3.0'\n" });
    assert.equal(expectManager(chooseManager(other, 'js', ['pnpm-lock.yaml']), 'pnpm'), undefined);
});


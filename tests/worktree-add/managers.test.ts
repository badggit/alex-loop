await test('a version query that times out is a mismatch with an unknown version', async (t) => {
    const binDir = path.join(tempRoot(t), 'bin');
    writeStubTool(binDir, 'pnpm', `exec '${realToolPath('sleep', process.env)}' 60`);
    const deps = testDeps(stubEnv(binDir));
    t.after(() => deps.runner.terminateAll());
    const started = performance.now();
    const check = await checkManagerVersion(deps, 'pnpm', undefined, tempRoot(t), 300);
    assert.ok(performance.now() - started < 10_000);
    assert.equal(check.kind, 'mismatch');
    assert.ok(check.kind === 'mismatch' && check.found.startsWith('unknown'), JSON.stringify(check));
});

await test('a failing or silent version query is a mismatch with an unknown version', async (t) => {
    const binDir = path.join(tempRoot(t), 'bin');
    writeStubTool(binDir, 'npm', 'exit 3');
    writeStubTool(binDir, 'bun', 'echo no version here');
    const deps = testDeps(stubEnv(binDir));
    const failed = await checkManagerVersion(deps, 'npm', undefined, tempRoot(t));
    assert.equal(failed.kind, 'mismatch');
    assert.ok(failed.kind === 'mismatch' && failed.found.startsWith('unknown ('), JSON.stringify(failed));
    const silent = await checkManagerVersion(deps, 'bun', undefined, tempRoot(t));
    assert.equal(silent.kind, 'mismatch');
    assert.ok(silent.kind === 'mismatch' && silent.found.startsWith('unknown ('), JSON.stringify(silent));
});

await test('a real pnpm lock is accepted by the real pnpm', async (t) => {
    const pnpm = toolOrSkip(t, 'pnpm');
    if (pnpm === undefined) {
        return;
    }
    const dir = project(t, { 'package.json': EMPTY_PACKAGE });
    const deps = testDeps(process.env);
    const install = await deps.runner.run({ file: pnpm, args: ['install', '--offline'], cwd: dir, timeoutMs: 60_000 });
    if (install.code !== 0 || !fs.existsSync(path.join(dir, 'pnpm-lock.yaml'))) {
        t.skip(`pnpm install --offline failed: ${install.stderr.trim() || install.stdout.trim()}`);
        return;
    }
    const expected = expectVersion(chooseManager(dir, 'js', ['pnpm-lock.yaml']), 'pnpm');
    const check = await checkManagerVersion(deps, 'pnpm', expected, dir);
    assert.equal(check.kind, 'ok', JSON.stringify(check));
});

await test('a real yarn 1 lock picks yarn-classic and the real yarn 1 matches it', async (t) => {
    const yarn = toolOrSkip(t, 'yarn');
    if (yarn === undefined) {
        return;
    }
    const deps = testDeps(process.env);
    const probe = await checkManagerVersion(deps, 'yarn-classic', undefined, tempRoot(t));
    if (probe.kind !== 'ok' || !probe.version.startsWith('1.')) {
        t.skip(`yarn on PATH is not yarn 1: ${JSON.stringify(probe)}`);
        return;
    }
    const dir = project(t, { 'package.json': EMPTY_PACKAGE });
    const install = await deps.runner.run({ file: yarn, args: ['install', '--offline'], cwd: dir, timeoutMs: 60_000 });
    if (install.code !== 0 || !fs.existsSync(path.join(dir, 'yarn.lock'))) {
        t.skip(`yarn install --offline failed: ${install.stderr.trim() || install.stdout.trim()}`);
        return;
    }
    const expected = expectVersion(chooseManager(dir, 'js', ['yarn.lock']), 'yarn-classic');
    const check = await checkManagerVersion(deps, 'yarn-classic', expected, dir);
    assert.equal(check.kind, 'ok', JSON.stringify(check));
});

await test('the real yarn 1 against a berry lock is a mismatch and leaves the lock untouched', async (t) => {
    if (toolOrSkip(t, 'yarn') === undefined) {
        return;
    }
    const deps = testDeps(process.env);
    const probe = await checkManagerVersion(deps, 'yarn-classic', undefined, tempRoot(t));
    if (probe.kind !== 'ok' || !probe.version.startsWith('1.')) {
        t.skip(`yarn on PATH is not yarn 1: ${JSON.stringify(probe)}`);
        return;
    }
    const dir = project(t, { 'package.json': EMPTY_PACKAGE, 'yarn.lock': BERRY_LOCK });
    const before = fs.readFileSync(path.join(dir, 'yarn.lock'));
    const expected = expectVersion(chooseManager(dir, 'js', ['yarn.lock']), 'yarn-berry');
    const check = await checkManagerVersion(deps, 'yarn-berry', expected, dir);
    assert.deepEqual(check, { kind: 'mismatch', expected: 'yarn 2 or newer', found: probe.version });
    assert.deepEqual(fs.readFileSync(path.join(dir, 'yarn.lock')), before);
});
